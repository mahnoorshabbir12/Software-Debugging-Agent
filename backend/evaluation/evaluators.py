from typing import Any
from langsmith.evaluation import EvaluationResult
from langsmith.schemas import Run, Example

def recall_evaluator(run: Run, example: Example) -> EvaluationResult:
    """
    Evaluates if the expected files were successfully retrieved by the 'search_code' tool
    during the agent's investigation.
    """
    expected_files = example.outputs.get("expected_files", [])
    if not expected_files:
        return EvaluationResult(key="recall", score=1.0, comment="No expected files to retrieve.")
        
    found_files = set()
    
    # Recursively search through child runs for 'search_code' tool calls
    def search_for_tools(current_run: Run):
        # LangSmith captures tool calls with run_type="tool"
        if current_run.run_type == "tool" and current_run.name == "search_code":
            # The tool output might contain the filenames
            # In our case, the tool output string usually lists file paths or content
            # We can check if the expected file paths are mentioned in the inputs or outputs
            output_str = str(current_run.outputs).lower()
            input_str = str(current_run.inputs).lower()
            
            for expected_file in expected_files:
                # Naive check: is the filename in the tool's input or output?
                if expected_file.lower() in output_str or expected_file.lower() in input_str:
                    found_files.add(expected_file)
                    
        for child in current_run.child_runs or []:
            search_for_tools(child)

    search_for_tools(run)
    
    score = len(found_files) / len(expected_files)
    
    return EvaluationResult(
        key="recall", 
        score=score, 
        comment=f"Found {len(found_files)} out of {len(expected_files)} expected files."
    )

def reasoning_evaluator(run: Run, example: Example) -> EvaluationResult:
    """
    Checks if the final root cause diagnosis generated by the agent contains the expected keywords.
    """
    expected_keywords = example.outputs.get("expected_root_cause_keywords", [])
    if not expected_keywords:
        return EvaluationResult(key="reasoning_accuracy", score=1.0)
        
    # The final output of the SupervisorGraph usually contains the final_root_cause or patch
    # We can inspect the final output string of the top-level run
    final_output_str = str(run.outputs).lower()
    
    found_keywords = []
    for kw in expected_keywords:
        if kw.lower() in final_output_str:
            found_keywords.append(kw)
            
    score = len(found_keywords) / len(expected_keywords)
    return EvaluationResult(
        key="reasoning_accuracy",
        score=score,
        comment=f"Found {len(found_keywords)} out of {len(expected_keywords)} keywords."
    )

def patch_evaluator(run: Run, example: Example) -> EvaluationResult:
    """
    Checks if the validation phase passed successfully for the patch.
    """
    # The SupervisorGraph outputs state. If validation passed, validation_result.passed == True
    # We look for "validation_result" in the root run outputs.
    outputs = run.outputs or {}
    
    # LangGraph state is usually returned directly
    val_result = outputs.get("validation_result")
    
    if val_result:
        # Pydantic or dict check
        passed = val_result.get("passed", False) if isinstance(val_result, dict) else getattr(val_result, "passed", False)
        return EvaluationResult(
            key="patch_success",
            score=1.0 if passed else 0.0,
            comment="Patch validation passed" if passed else "Patch validation failed"
        )
        
    # If we didn't find validation_result, it might mean the agent failed before patching
    return EvaluationResult(
        key="patch_success",
        score=0.0,
        comment="No validation result found in final state."
    )
